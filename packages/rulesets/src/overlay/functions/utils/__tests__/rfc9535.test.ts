import { validateJsonPath } from '../rfc9535';

describe('RFC 9535 JSONPath syntax validation', () => {
  it.each([
    '$',
    '$.store.book',
    '$.store.*',
    '$..author',
    '$..*',
    '$..[0]',
    '$.o.j',
    "$['store']['book']",
    '$["a\\"b"]',
    "$['\\u00e9\\uD83D\\uDE00']",
    '$.é',
    '$._a1',
    '$[0]',
    '$[-1]',
    '$[0, 1]',
    "$['a','b']",
    '$[ 0 , 1 ]',
    '$[:]',
    '$[1:3]',
    '$[::2]',
    '$[5:1:-2]',
    '$[ 1 : 3 : 1 ]',
    '$[*]',
    '$[?@.isbn]',
    '$[?(@.isbn)]',
    '$[?@.price < 10]',
    "$[?@.category == 'fiction' && @.price <= 8.95]",
    '$[?@.a || !@.b]',
    '$[?!(@.a == 1)]',
    '$[?@.a == -0]',
    '$[?@.a == 1.5e-3]',
    '$[?@.a == true || @.b == null || @.c == false]',
    '$[?@.a == $.b]',
    "$[?@['a'][0] == 1]",
    '$[?length(@.tags) >= 2]',
    '$[?count(@.*) == 1]',
    "$[?match(@.date, '1974-05-..')]",
    "$[?search(@.author, '[BR]ob')]",
    '$[?value(@..color) == "red"]',
    '$[?length(value(@.*)) == 1]',
    '$[?@.*]',
    '$[?@..a]',
    '$[?@[?@.b]]',
    '$.paths.*.*[?@.tags && length(@.tags) > 1]',
    '$ .a',
    '$[?(@.price < 10)].title.length',
    '$\t[0]',
  ])('accepts %s', query => {
    expect(validateJsonPath(query)).toBeNull();
  });

  it.each([
    ['', 'must start with the root identifier'],
    ['paths', 'must start with the root identifier'],
    ['@.a', 'must start with the root identifier'],
    ['$.', 'expected a member name'],
    ['$.1a', 'expected a member name'],
    ['$.a-b', 'unexpected character "-"'],
    ['$[', 'expected a selector'],
    ['$[0', 'expected "]"'],
    ['$[]', 'expected a selector'],
    ['$[01]', 'leading zeros'],
    ['$[-0]', '"-0" is not a valid integer'],
    ['$[9007199254740992]', 'out of the I-JSON range'],
    ['$[0,]', 'expected a selector'],
    ["$['a]", 'unterminated string literal'],
    ["$['\\x']", 'invalid escape sequence'],
    ["$['\\uD800']", 'low surrogate'],
    ['$[?(@.a == 1)]^', 'unexpected character "^"'],
    ['$..', 'expected a member name'],
    ['$...a', 'expected a member name'],
    ['$[?@property === "x"]', 'expected "]" but found character "p"'],
    ['$[?@.a = 1]', 'expected "]"'],
    ['$[?@.a === 1]', 'expected a literal, query or function expression'],
    ['$[?1]', 'literals must be compared'],
    ['$[?@.* == 1]', 'only singular queries can be compared'],
    ['$[?@..a == 1]', 'only singular queries can be compared'],
    ['$[?@[0, 1] == 1]', 'only singular queries can be compared'],
    ['$[?length(@.a)]', 'must be compared'],
    ["$[?match(@.a, 'x') == true]", 'cannot be compared'],
    ['$[?foo(@.a)]', 'unknown function "foo"'],
    ['$[?length(@.a, 1)]', 'expects 1 argument but got 2'],
    ['$[?count(1) == 1]', 'argument 1 of function "count" must be of NodesType'],
    ['$[?length(@.*) == 1]', 'argument 1 of function "length" must be of ValueType'],
    ['$[?@.a == 01]', 'leading zeros'],
    ['$[?@.a == 1.]', 'expected a digit'],
    ['$[?@.a == True]', 'expected a literal, query or function expression but found character "T"'],
    ['$[?(@.a == 1]', 'expected ")"'],
    ['$[?@.a == 1 == 2]', 'expected "]"'],
    ['$[?(@.a) == 1]', 'logical expressions cannot be compared'],
    ['$[?!1]', 'cannot be applied to a literal'],
    ['$.a ', 'unexpected character " "'],
  ])('rejects %s', (query, message) => {
    const error = validateJsonPath(query);
    expect(error).not.toBeNull();
    expect(error?.message).toContain(message);
  });
});
